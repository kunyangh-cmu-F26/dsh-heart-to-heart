import { readFile, writeFile } from 'node:fs/promises'

const files = ['wire.js', 'listening.js', 'toolbar.js']
const sources = await Promise.all(files.map(file => readFile(new URL('../src/' + file, import.meta.url), 'utf8')))
const code = sources.map(source => source.replace(/^import .*\n/gm, '').replace(/^export /gm, '')).join('\n')
await writeFile(new URL('../lib/client.js', import.meta.url), `// Generated by npm run build.
window.__ModuleLoader__.load({
  id: 'dsh-heart-to-heart',
  factory: (require) => {
    const React = require('react')
${code}
    return { apply, inject: ['slots', 'sessions', 'conversation', 'locale', 'modules'] }
  },
})
`)
